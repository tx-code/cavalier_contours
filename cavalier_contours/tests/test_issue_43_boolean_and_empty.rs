use cavalier_contours::pline_closed;
use cavalier_contours::polyline::{BooleanOp, PlineSource};

#[test]
fn issue_43_boolean_and_should_not_be_empty() {
    // Repro from upstream issue #43:
    // https://github.com/jbuckmccready/cavalier_contours/issues/43
    let subject = pline_closed![
        (
            8.6284200000000002006572686,
            23.3550000000000004263256415,
            0.4142135623730941462738997
        ),
        (
            7.5199999999999995736743585,
            22.2465800000000015756995708,
            0.9999999999999998889776975
        ),
        (
            7.9199999999999999289457264,
            22.2465800000000015756995708,
            -0.4142135623730950344523194
        ),
        (
            8.6284200000000002006572686,
            22.9550000000000018474111130,
            0.9999999999999998889776975
        ),
    ];

    let clip = pline_closed![
        (
            8.4284199999999991348431649,
            22.9550000000000018474111130,
            0.0000000000000000000000000
        ),
        (
            10.1775000000000002131628207,
            22.9550000000000018474111130,
            1.0000000000000000000000000
        ),
        (
            10.1775000000000002131628207,
            23.3550000000000004263256415,
            0.0000000000000000000000000
        ),
        (
            8.4284199999999991348431649,
            23.3550000000000004263256415,
            0.4142135623730941462738997
        ),
        (
            7.3199999999999993960386746,
            22.2465800000000015756995708,
            0.0023624850393199510467657
        ),
        (
            7.3200000000000002842170943,
            22.2446899999999985197973729,
            0.0000000000000000000000000
        ),
        (
            7.3200000000000002842170943,
            17.0041299999999999670308171,
            1.0000000000000000000000000
        ),
        (
            7.9199999999999999289457264,
            17.0041299999999999670308171,
            0.0000000000000000000000000
        ),
        (
            7.9199999999999999289457264,
            22.2446899999999985197973729,
            0.2691108888045321556603540
        ),
        (
            7.7688725235674729319157450,
            22.5051453161804388969358115,
            -0.3085627603572850263802252
        ),
    ];

    let result = subject.boolean(&clip, BooleanOp::And);
    assert!(
        !result.pos_plines.is_empty(),
        "expected upstream #43 AND result to include at least one positive polyline"
    );
}
