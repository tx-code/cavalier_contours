fn create_cpp_static_index() -> StaticAABB2DIndex<f64> {
    let mut builder = StaticAABB2DIndexBuilder::new(CPP_STATIC_INDEX_TEST_DATA.len() / 4);
    for item in CPP_STATIC_INDEX_TEST_DATA.chunks_exact(4) {
        builder.add(item[0], item[1], item[2], item[3]);
    }
    builder
        .build()
        .expect("C++ static spatial index test data should build")
}

fn sorted_expected_indices() -> Vec<usize> {
    vec![6, 29, 31, 75]
}

#[test]
fn cpp_static_spatial_index_query_parity() {
    let index = create_cpp_static_index();
    let mut actual = index.query(40.0, 40.0, 60.0, 60.0);
    actual.sort_unstable();
    assert_eq!(actual, sorted_expected_indices());
}

#[test]
fn cpp_static_spatial_index_visit_query_parity() {
    let index = create_cpp_static_index();
    let mut actual = Vec::new();
    index.visit_query(40.0, 40.0, 60.0, 60.0, &mut |i| {
        actual.push(i);
    });
    actual.sort_unstable();
    assert_eq!(actual, sorted_expected_indices());
}

#[test]
fn cpp_static_spatial_index_visit_query_stops_early() {
    let index = create_cpp_static_index();
    let expected = sorted_expected_indices();
    let mut actual = Vec::new();

    index.visit_query(40.0, 40.0, 60.0, 60.0, &mut |i| -> Control<()> {
        actual.push(i);
        if actual.len() == 2 {
            Control::Break(())
        } else {
            Control::Continue
        }
    });

    assert_eq!(actual.len(), 2);
    for index in actual {
        assert!(
            expected.contains(&index),
            "early-stop result index should be in expected set, got {index}"
        );
    }
}
